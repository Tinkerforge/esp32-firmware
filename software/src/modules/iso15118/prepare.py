import glob
import os
import re
import struct
import sys

import tinkerforge_util as tfutil

tfutil.create_parent_module(__file__, 'software')

from software import util

# The QCA700x PLC modem firmware (*.nvm) is proprietary and not part of the public repository.
# If it is missing, the firmware is built without modem firmware update support.
FIRMWARE_DIR = 'qca_firmware'

# nvm_header2 from open-plc-utils nvm/nvm.h (96 bytes)
NVM_HEADER = struct.Struct('<HHIIIIIIIIIHHHH12I')
NVM_IMAGE_FIRMWARE = 0x0004
NVM_IMAGE_MANIFEST = 0x000E
NVM_IMAGE_PIB      = 0x000F


def fail(message):
    print(f'Error: QCA modem firmware: {message}', file=sys.stderr)
    sys.exit(1)


# Same as checksum32() in open-plc-utils and PibManager::fdchecksum32()
def checksum32(data):
    checksum = 0

    for (word,) in struct.iter_unpack('<I', data):
        checksum ^= word

    return ~checksum & 0xFFFFFFFF


def parse_chain(data, name):
    if len(data) == 0 or len(data) % 4 != 0:
        fail(f'{name} size {len(data)} is not a non-zero multiple of 4 bytes')

    images = []
    offset = 0

    while True:
        if offset + NVM_HEADER.size > len(data):
            fail(f'{name} header at 0x{offset:X} is truncated')

        fields = NVM_HEADER.unpack_from(data, offset)
        major_version, minor_version = fields[0], fields[1]
        image_nvm_address, image_length, image_checksum = fields[3], fields[5], fields[6]
        next_header, image_type, header_checksum = fields[8], fields[10], fields[-1]

        if (major_version, minor_version) != (1, 1):
            fail(f'{name} header at 0x{offset:X} has unsupported version {major_version}.{minor_version}')

        if checksum32(data[offset:offset + NVM_HEADER.size - 4]) != header_checksum:
            fail(f'{name} header at 0x{offset:X} has a bad checksum')

        image = data[image_nvm_address:image_nvm_address + image_length]

        if len(image) != image_length or checksum32(image) != image_checksum:
            fail(f'{name} image at 0x{image_nvm_address:X} is truncated or has a bad checksum')

        images.append((image_type, image))

        if next_header == 0xFFFFFFFF:
            break

        if next_header <= offset or len(images) >= 32:
            fail(f'{name} has a bad header chain')

        offset = next_header

    return images


def find_single_file(pattern):
    paths = sorted(glob.glob(os.path.join(FIRMWARE_DIR, pattern)))

    if len(paths) > 1:
        fail(f'More than one {pattern} file found in {FIRMWARE_DIR}: {", ".join(paths)}')

    return paths[0] if len(paths) > 0 else None


def get_manifest_string(images, regex, name):
    if len(images) == 0 or images[0][0] != NVM_IMAGE_MANIFEST:
        fail(f'{name} does not start with a chain manifest')

    m = re.search(regex, images[0][1])

    if m == None:
        fail(f'{name} manifest does not contain a version string')

    return m


# The manifest contains a build version string like
#   FW-QCA7006-3.6.0.0041-00-CS-20260923:235249-Custom:Custom-2-1.5
# The modem reports the running firmware in VS_SW_VER.CNF as
#   MAC-QCA7006-HPGP-3.6.0.41-00-20260923-CS
# with a device-specific prefix. Return the part after the prefix: 3.6.0.41-00-20260923-CS
def get_sw_version(images, prefix, name):
    m = get_manifest_string(images, prefix + rb'-QCA[0-9A-Za-z]+-(\d+)\.(\d+)\.(\d+)\.(\d+)-(\d+)-([A-Za-z]+)-(\d{8}):', name)
    major, minor, subversion, build, sustaining, build_type, date = [x.decode('ascii') for x in m.groups()]

    return f'{major}.{minor}.{subversion}.{int(build)}-{sustaining}-{date}-{build_type}'


def main():
    os.makedirs('generated', exist_ok=True)

    nvm_path = find_single_file('*.nvm')

    if nvm_path == None:
        print('QCA modem firmware not found, building without modem firmware update support')
        util.write_generated_file(os.path.join('generated', 'qca_firmware.h'),
                                  '// WARNING: This file is generated by prepare.py\n\n'
                                  '#pragma once\n\n'
                                  '#define QCA_FIRMWARE_AVAILABLE 0\n')
        return

    pib_path = find_single_file('*.pib')

    if pib_path == None:
        fail(f'Found {nvm_path}, but no PIB in {FIRMWARE_DIR}')

    with open(nvm_path, 'rb') as f:
        nvm = f.read()

    with open(pib_path, 'rb') as f:
        pib = f.read()

    nvm_images = parse_chain(nvm, nvm_path)
    pib_images = parse_chain(pib, pib_path)

    if NVM_IMAGE_FIRMWARE not in [image_type for image_type, _ in nvm_images]:
        fail(f'{nvm_path} does not contain a runtime firmware image')

    if [image_type for image_type, _ in pib_images] != [NVM_IMAGE_MANIFEST, NVM_IMAGE_PIB]:
        fail(f'{pib_path} is not a PIB with manifest')

    nvm_version = get_sw_version(nvm_images, rb'FW', nvm_path)
    pib_version = get_sw_version(pib_images, rb'PIB', pib_path)

    print(f'Embedding QCA modem firmware {nvm_version} with PIB {pib_version}')

    util.embed_data_with_digest(nvm, 'generated', 'qca_firmware_nvm', 'uint8_t')
    util.embed_data_with_digest(pib, 'generated', 'qca_firmware_pib', 'uint8_t')

    util.write_generated_file(os.path.join('generated', 'qca_firmware.h'),
                              '// WARNING: This file is generated by prepare.py\n\n'
                              '#pragma once\n\n'
                              '#define QCA_FIRMWARE_AVAILABLE 1\n'
                              f'#define QCA_FIRMWARE_VERSION "{nvm_version}"\n'
                              f'#define QCA_FIRMWARE_PIB_VERSION "{pib_version}"\n\n'
                              '#include "qca_firmware_nvm.embedded.h"\n'
                              '#include "qca_firmware_pib.embedded.h"\n')


main()
